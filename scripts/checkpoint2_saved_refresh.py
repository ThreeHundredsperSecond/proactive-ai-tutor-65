FILES = ['summary.json','manifest.json','review-queue.json','report.md','provenance.json',
         'figures/progression.png','figures/new65-audit.png']


def load(root):
    root = Path(root)
    out = root/REL
    hashes = {str(REL/p).replace('\\','/'):hashlib.sha256((out/p).read_bytes()).hexdigest() for p in FILES}
    summary = json.loads((out/'summary.json').read_text(encoding='utf-8'))
    manifest = json.loads((out/'manifest.json').read_text(encoding='utf-8'))
    assert len(manifest) == len({r['task_id'] for r in manifest}) == 315
    assert summary['new_pairs'] == 65 and summary['not_processed'] == 35
    assert summary['prior100_regression'] and summary['prior250_regression']
    assert summary['populations']['baseline100']['included_n'] == 98
    return summary, hashes


